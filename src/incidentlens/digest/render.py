"""Render periodic Markdown digests for lower-priority alerts."""

from __future__ import annotations

from datetime import datetime

from incidentlens.markdown import md_code, md_link, md_text, md_url
from incidentlens.models import CONFIDENCE_LABEL, AlertGroup


def _time(dt: datetime, ref: datetime) -> str:
    return dt.strftime("%H:%M") if dt.date() == ref.date() else dt.strftime("%m-%d %H:%M")


def _render_incident(index: int, inc: AlertGroup, ref: datetime) -> list[str]:
    status = "🔥 ongoing" if inc.is_ongoing else "✅ resolved"
    lines = [
        f"## {inc.severity.icon} #{index} {md_text(inc.name)} · {md_code(inc.service)}",
        f"- **Owner:** {md_text(inc.team)}",
        f"- **Window:** {_time(inc.first_seen, ref)} → {_time(inc.last_seen, ref)} (UTC)",
        f"- **Status:** {status}",
        f"- **Alert count:** {inc.receive_count} (from {len(inc.records)} source(s))",
        f"- **Summary:** {md_text(inc.summary)}",
    ]
    if inc.escalated:
        lines.append("- **Escalation:** ⬆️ automatically escalated to 🔴 and paged on-call")
    if inc.changes:
        lines.append("- **Recent changes:**")
        for ch in inc.changes:
            who = f" by {md_text(ch.author)}" if ch.author else ""
            safe_ch_url = md_url(ch.url)
            ref_code = md_code(ch.ref)
            ref_text = f"[{ref_code}]({safe_ch_url})" if safe_ch_url else ref_code
            lines.append(f"  - {md_text(ch.kind)} {ref_text}{who} at {_time(ch.created_at, ref)}")
    if inc.investigation and inc.investigation.hypotheses:
        top = inc.investigation.hypotheses[0]
        links = " · ".join(md_link(e.description, e.url) for e in inc.investigation.evidence_for(top))
        lines.append(f"- **Hypothesis [{CONFIDENCE_LABEL[top.confidence]}]:** {md_text(top.statement)}")
        lines.append(f"  - Evidence: {links}")
    safe_source = md_url(inc.source_url)
    if safe_source:
        lines.append(f"- **Source:** [View in monitoring]({safe_source})")
    return lines


def render_digest(incidents: list[AlertGroup], window_start: datetime, window_end: datetime) -> str:
    title = f"# 📋 Digest {window_end:%Y-%m-%d} · {_time(window_start, window_end)}–{window_end:%H:%M} (UTC)"
    lines = [title, ""]

    if not incidents:
        lines += ["> No alerts recorded in this window. 🎉", ""]
        return "\n".join(lines)

    total = sum(i.receive_count for i in incidents)
    summary = f"> {total} alerts → {len(incidents)} groups."
    focus = next((n for n, inc in enumerate(incidents, 1) if inc.is_ongoing), None)
    if focus:
        summary += f" **Priority: #{focus}**"
    lines += [summary, "", "## Action items"]

    for n, inc in enumerate(incidents, 1):
        box = "[ ]" if inc.is_ongoing else "[x]"
        tail = "" if inc.is_ongoing else " — auto-resolved"
        lines.append(
            f"- {box} {inc.severity.icon} #{n} {md_code(inc.service)} {md_text(inc.name)} — {md_text(inc.team)}{tail}"
        )

    lines += ["", "---"]
    for n, inc in enumerate(incidents, 1):
        lines += ["", *_render_incident(n, inc, window_end)]

    lines += [
        "",
        "---",
        f"_Generated by IncidentLens at {window_end:%Y-%m-%d %H:%M} UTC. "
        "Alert severity is determined by static routing rules, not AI. "
        "Hypotheses are suggestions requiring human verification._",
        "",
    ]
    return "\n".join(lines)
